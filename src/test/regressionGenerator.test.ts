import { describe, it, expect } from 'vitest';
import { RegressionTestGenerator } from '../domain/remediation/RegressionTestGenerator';
import type { VulnerabilityFinding } from '../types';

describe('RegressionTestGenerator (Automated Test Synthesis)', () => {
  const sampleFinding: VulnerabilityFinding = {
    id: 'FIND-SQLI-001',
    title: 'SQL Injection in User Search',
    severity: 'critical',
    cweId: 'CWE-89',
    owaspCategory: 'A03:2021-Injection',
    targetEndpoint: 'https://api.acme.corp/v1/users/search',
    description: 'Direct concatenation of user parameter into SQL statement.',
    remediation: 'Use parameterized queries.',
    status: 'open',
  };

  it('generates PyTest regression suite with explicit unexecuted badge', () => {
    const suite = RegressionTestGenerator.generatePyTest(sampleFinding);

    expect(suite.framework).toBe('pytest');
    expect(suite.wasExecuted).toBe(false);
    expect(suite.fileName).toBe('test_find-sqli-001_regression.py');
    expect(suite.testCode).toContain('import pytest');
    expect(suite.testCode).toContain('assert response.status_code != 500');
    expect(suite.testCode).toContain('[NOTICE] Generated by Nexus AI Security Workbench');
    expect(suite.verificationCommand).toBe('pytest test_find-sqli-001_regression.py -v');
  });

  it('generates Jest test with assert status checks', () => {
    const suite = RegressionTestGenerator.generateJest(sampleFinding);

    expect(suite.framework).toBe('jest');
    expect(suite.wasExecuted).toBe(false);
    expect(suite.testCode).toContain("describe('Security Regression");
    expect(suite.testCode).toContain('expect(response.status).not.toBe(500)');
  });

  it('generates cURL bash test script with status code exit evaluation', () => {
    const suite = RegressionTestGenerator.generateCurlScript(sampleFinding);

    expect(suite.framework).toBe('curl');
    expect(suite.wasExecuted).toBe(false);
    expect(suite.testCode).toContain('#!/usr/bin/env bash');
    expect(suite.testCode).toContain('curl -s -o /dev/null -w "%{http_code}"');
  });
});

