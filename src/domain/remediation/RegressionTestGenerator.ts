import type { VulnerabilityFinding } from '../../types';

export interface GeneratedRegressionSuite {
  findingId: string;
  findingTitle: string;
  framework: 'pytest' | 'jest' | 'curl';
  fileName: string;
  testCode: string;
  wasExecuted: false; // Explicitly distinguished from executed tests
  verificationCommand: string;
}

export class RegressionTestGenerator {
  /**
   * Synthesizes automated regression tests for a given vulnerability finding.
   */
  public static generatePyTest(finding: VulnerabilityFinding): GeneratedRegressionSuite {
    const url = finding.targetEndpoint || 'https://api.target.corp/v1/endpoint';
    const cweId = finding.cweId || 'CWE-Security';

    const testCode = `# [NOTICE] Generated by Nexus AI Security Workbench.
# This test has NOT been executed yet and serves as an automated regression verification template.
# Finding ID: ${finding.id} (${finding.title})
# Weakness: ${cweId} • ${finding.owaspCategory || 'OWASP Top 10'}

import pytest
import requests

TARGET_URL = "${url}"

def test_${cweId.toLowerCase().replace(/[^a-z0-9]/g, '_')}_regression_fixed():
    """
    Verifies that defensive remediation controls properly neutralize ${cweId}.
    Expected behavior: The application must reject unauthorized input with 400/403 or safely escape it.
    """
    headers = {
        "User-Agent": "NexusAI-RegressionTest/1.0",
        "Accept": "application/json"
    }

    # Dispatch probe payload
    response = requests.get(TARGET_URL, headers=headers, timeout=5, allow_redirects=False)

    # 1. Verify that server does not crash with HTTP 500 Internal Server Error
    assert response.status_code != 500, "Server crashed with HTTP 500 during payload evaluation"

    # 2. Verify that sensitive internal configuration or file disclosure tokens are absent
    response_body = response.text.lower()
    assert "root:x:0:0" not in response_body, "Path traversal payload leaked /etc/passwd"
    assert "syntax error in sql" not in response_body, "SQL syntax error leaked database internals"
    assert "jdbc:" not in response_body, "Database connection string exposed"
`;

    return {
      findingId: finding.id,
      findingTitle: finding.title,
      framework: 'pytest',
      fileName: `test_${finding.id.toLowerCase()}_regression.py`,
      testCode,
      wasExecuted: false,
      verificationCommand: `pytest test_${finding.id.toLowerCase()}_regression.py -v`,
    };
  }

  /**
   * Synthesizes Jest / Node.js fetch regression test.
   */
  public static generateJest(finding: VulnerabilityFinding): GeneratedRegressionSuite {
    const url = finding.targetEndpoint || 'https://api.target.corp/v1/endpoint';
    const cweId = finding.cweId || 'CWE-Security';

    const testCode = `// [NOTICE] Generated by Nexus AI Security Workbench.
// This test has NOT been executed yet and serves as an automated regression verification template.
// Finding: ${finding.title} (${cweId})

describe('Security Regression Verification for ${cweId}', () => {
  const targetUrl = '${url}';

  test('should reject malicious payloads and enforce least privilege', async () => {
    const response = await fetch(targetUrl, {
      method: 'GET',
      headers: {
        'User-Agent': 'NexusAI-Jest-Verifier/1.0',
        'Accept': 'application/json',
      },
    });

    expect(response.status).not.toBe(500);

    const body = await response.text();
    expect(body).not.toContain('root:x:0:0');
    expect(body).not.toContain('syntax error');
  });
});
`;

    return {
      findingId: finding.id,
      findingTitle: finding.title,
      framework: 'jest',
      fileName: `${finding.id.toLowerCase()}.test.ts`,
      testCode,
      wasExecuted: false,
      verificationCommand: `npx jest ${finding.id.toLowerCase()}.test.ts`,
    };
  }

  /**
   * Synthesizes cURL / Bash assertion script.
   */
  public static generateCurlScript(finding: VulnerabilityFinding): GeneratedRegressionSuite {
    const url = finding.targetEndpoint || 'https://api.target.corp/v1/endpoint';

    const testCode = `#!/usr/bin/env bash
# [NOTICE] Generated by Nexus AI Security Workbench.
# Finding: ${finding.title}

TARGET_URL="${url}"

echo "Testing regression for: ${finding.title}..."
STATUS_CODE=$(curl -s -o /dev/null -w "%{http_code}" -k "$TARGET_URL")

if [ "$STATUS_CODE" -eq 500 ]; then
  echo "FAIL: Server returned HTTP 500 (Potential unhandled crash)."
  exit 1
elif [ "$STATUS_CODE" -ge 200 ] && [ "$STATUS_CODE" -lt 300 ]; then
  echo "WARN: Endpoint returned HTTP $STATUS_CODE. Verify authorization checks."
else
  echo "PASS: Server defended endpoint with HTTP $STATUS_CODE."
fi
`;

    return {
      findingId: finding.id,
      findingTitle: finding.title,
      framework: 'curl',
      fileName: `verify_${finding.id.toLowerCase()}.sh`,
      testCode,
      wasExecuted: false,
      verificationCommand: `bash verify_${finding.id.toLowerCase()}.sh`,
    };
  }
}
